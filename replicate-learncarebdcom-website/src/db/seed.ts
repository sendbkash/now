let seeding: Promise<void> | null = null;

export function ensureSeed(): Promise<void> {
  if (!seeding) {
    seeding = (async () => {
      const [{ courses: courseCount }] = await db.select({ courses: count() }).from(courses);
      const [{ tools: toolCount }] = await db.select({ tools: count() }).from(tools);
      if (courseCount === 0) await db.insert(courses).values(courseSeed);
      if (toolCount === 0) await db.insert(tools).values(toolSeed);
    })().catch((error) => {
      seeding = null;
      throw error;
    });
  }
  return seeding;
}
